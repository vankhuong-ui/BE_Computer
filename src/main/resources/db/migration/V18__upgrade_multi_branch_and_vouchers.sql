-- 2. Multi-Branch Inventory (1 Product x 1 Branch)
ALTER TABLE inventory
    ADD COLUMN IF NOT EXISTS branch_id BIGINT;

ALTER TABLE inventory
    DROP CONSTRAINT IF EXISTS inventory_product_id_key;

UPDATE inventory
SET branch_id = (SELECT id FROM branches ORDER BY id ASC LIMIT 1)
WHERE branch_id IS NULL;

ALTER TABLE inventory
    ALTER COLUMN branch_id SET NOT NULL;

ALTER TABLE inventory
    DROP CONSTRAINT IF EXISTS fk_inventory_branch;

ALTER TABLE inventory
    ADD CONSTRAINT fk_inventory_branch
        FOREIGN KEY (branch_id) REFERENCES branches(id) ON DELETE CASCADE;

ALTER TABLE inventory
    DROP CONSTRAINT IF EXISTS uk_inventory_product_branch;

ALTER TABLE inventory
    ADD CONSTRAINT uk_inventory_product_branch
        UNIQUE (product_id, branch_id);

-- 3. Categories Group Type (LAPTOP | PC | ACCESSORY) & Products image TEXT
ALTER TABLE categories
    ADD COLUMN IF NOT EXISTS group_type VARCHAR(50) NOT NULL DEFAULT 'LAPTOP';

UPDATE categories
SET group_type = CASE
    WHEN LOWER(name_categories) SIMILAR TO '%(phụ kiện|chuột|bàn phím|tai nghe|balo|túi|sạc|cáp|hub|ram|ssd|ổ cứng|linh kiện)%' THEN 'ACCESSORY'
    WHEN LOWER(name_categories) SIMILAR TO '%(pc|máy bàn|workstation|màn hình|monitor|desktop)%' THEN 'PC'
    ELSE 'LAPTOP'
END;

ALTER TABLE products
    ALTER COLUMN image TYPE TEXT;

-- 4. Vouchers (Ưu đãi đơn đầu & Mã giảm giá thương mại — không cần bảng phụ voucher_usages)
CREATE TABLE IF NOT EXISTS vouchers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    title VARCHAR(255) NOT NULL,
    description VARCHAR(500),
    discount_type VARCHAR(20) NOT NULL DEFAULT 'FIXED',
    discount_value DECIMAL(19,2) NOT NULL,
    max_discount DECIMAL(19,2),
    min_order_amount DECIMAL(19,2) NOT NULL DEFAULT 0,
    first_order_only BOOLEAN NOT NULL DEFAULT FALSE,
    usage_limit INT NOT NULL DEFAULT 1000,
    used_count INT NOT NULL DEFAULT 0,
    start_date TIMESTAMP,
    end_date TIMESTAMP,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

