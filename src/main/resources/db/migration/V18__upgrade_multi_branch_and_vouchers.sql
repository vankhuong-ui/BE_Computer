-- 5. Orders & Order Items (Fulfillment by Branch + Voucher Discount)
ALTER TABLE orders
    ADD COLUMN IF NOT EXISTS fulfillment_type VARCHAR(30) NOT NULL DEFAULT 'HOME_DELIVERY',
    ADD COLUMN IF NOT EXISTS pickup_branch_id BIGINT,
    ADD COLUMN IF NOT EXISTS receiver_name VARCHAR(255),
    ADD COLUMN IF NOT EXISTS receiver_phone VARCHAR(50),
    ADD COLUMN IF NOT EXISTS voucher_id BIGINT,
    ADD COLUMN IF NOT EXISTS voucher_code VARCHAR(50),
    ADD COLUMN IF NOT EXISTS discount_amount DECIMAL(19,2) NOT NULL DEFAULT 0;

