CREATE TABLE cart (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                      product_id BIGINT,
                      account_id BIGINT,
                      quality INT,

                      CONSTRAINT fk_cart_products
                          FOREIGN KEY (product_id)
                              REFERENCES products(id),

                      CONSTRAINT fk_cart_account
                          FOREIGN KEY (account_id)
                              REFERENCES account(id)
);
